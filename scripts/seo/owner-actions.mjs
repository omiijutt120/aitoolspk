#!/usr/bin/env node
/**
 * Build the one page the owner works from.
 *
 * Everything a machine can do is done; what is left needs an account, a phone
 * or a conversation. This file states those few actions in order, with the
 * exact link or command, and computes the counts from the repository instead of
 * repeating numbers in prose that go stale the next time the catalogue changes.
 *
 *   npm run seo:owner-actions
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { parseCsv } from '../lib/csv.mjs';
import { publicationReadiness } from '../catalog/quotes.mjs';

const readJson = (file, fallback) =>
  existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : fallback;

const catalog = JSON.parse(readFileSync('data/catalog.json', 'utf8'));
const backlinks = parseCsv(readFileSync('data/seo/backlinks.csv', 'utf8'));
const bingAuth = existsSync('public/BingSiteAuth.xml')
  ? readFileSync('public/BingSiteAuth.xml', 'utf8')
  : '';
const bingUser = bingAuth.match(/<user>\s*([^<\s]+)\s*<\/user>/i)?.[1] ?? '';
const indexStatus = readJson(
  path.join('reports', 'gsc', 'index-status.json'),
  null
);
const editorialRaw = readJson('data/seo/editorial.json', []);
const reviews = Array.isArray(editorialRaw)
  ? Object.fromEntries(
      editorialRaw
        .filter((review) => review.id)
        .map((review) => [review.id, review])
    )
  : editorialRaw;

const pending = catalog.filter((product) => product.approval === 'pending');
const quoteDates = [...new Set(pending.map((product) => product.date))].sort();
const byDate = quoteDates.map((date) => ({
  date,
  count: pending.filter((product) => product.date === date).length,
}));
const readiness = publicationReadiness(catalog, reviews);
const submitted = backlinks.filter((row) => row.status);
const firstFive = backlinks
  .filter((row) => !row.status)
  .slice(0, 5)
  .map((row) => row.platform);

const lines = [
  '# Owner actions — the five things only you can do',
  '',
  'Generated by `npm run seo:owner-actions`. Every count below is read from the',
  'repository, so nothing here can drift from the catalogue.',
  '',
  '## What is already done and deployed',
  '',
  '- 188 sitemap URLs, all self-canonical, zero `noindex` inside the sitemap.',
  '- IndexNow submits the live sitemap after every successful deploy.',
  '- `llms.txt`, `llms-full.txt` and `ai.txt` are generated from the catalogue.',
  '- The dead `hello@aitoolspk.tech` address is gone from every page and asset.',
  '- Titles, H1s and descriptions measured against the Search Console export.',
  '',
  '## 1. Bing Webmaster Tools — click Verify (2 minutes)',
  '',
  `Open <https://www.bing.com/webmasters/> and verify \`aitoolspk.tech\`. The file`,
  `Bing asks for is already published at <https://aitoolspk.tech/BingSiteAuth.xml>${
    bingUser ? ` with user code \`${bingUser}\`` : ''
  }.`,
  '',
  'Discovery no longer waits on this — IndexNow already submits every deploy —',
  "but verification is the only way to see Bing's index status and crawl errors,",
  'and Bing feeds Copilot.',
  '',
  '## 2. Search Console — request indexing, then read the verdict',
  '',
  'Request Indexing has no API and stays a click. The queue is already built:',
  '',
  '```',
  'npm run gsc:queue',
  '```',
  '',
  'Open `reports/gsc/request-indexing.html` and work down the list. Each link',
  'opens URL Inspection with the URL filled in.',
  '',
  indexStatus
    ? `Last URL Inspection run: ${indexStatus.checkedAt}, ${indexStatus.inspected}/${indexStatus.sitemapUrls} URLs, ${indexStatus.notIndexed?.length ?? 0} not passing.`
    : "No URL Inspection run yet. To read Google's verdict for all 188 URLs instead of guessing:",
  '',
  '```',
  'npm run gsc:sites            # confirm the property identifier',
  'npm run gsc:inspect          # reads reports/gsc/index-status.csv',
  'npm run gsc:queue            # rebuilds the click list from that verdict',
  'npm run gsc:export           # refreshes queries/pages without a manual export',
  '```',
  '',
  'These need a Search Console service account added as a user on the property.',
  'The script prints the exact steps when no credential is configured.',
  '',
  '## 3. Seller data — one conversation, then one command',
  '',
  `**${pending.length} listings** are \`pending\`, quoted on ${byDate
    .map((entry) => `${entry.date} (${entry.count})`)
    .join(', ')}.`,
  `${readiness.APPROVED_INDEXABLE ?? 0} listings are currently indexable; ${readiness.NEEDS_REVIEW ?? 0} need review and ${readiness.EXCLUDED ?? 0} are excluded.`,
  '',
  '```',
  'npm run catalog:quote-request                  # one CSV for all pending rows',
  'npm run catalog:quote-request -- --collection netflix   # or one collection',
  'npm run catalog:quote-apply -- --quote-date YYYY-MM-DD   # after it comes back',
  '```',
  '',
  'The request sheet asks for price, confirmation, warranty, access and renewal.',
  'A blank cell changes nothing; `approval` is never touched by the apply step.',
  'Unlocking `/tool/` pages also needs commercial authorization and an editorial',
  'review per product — a price is not permission, and the site does not claim',
  'either one it does not have.',
  '',
  '## 4. Backlinks — the binding constraint',
  '',
  `${backlinks.length} targets are prepared in \`data/seo/backlinks.csv\`; ${
    submitted.length
  } submitted so far${submitted.length ? ` (${submitted.map((row) => row.platform).join(', ')})` : ''}.`,
  `Start with: ${firstFive.join(', ')}.`,
  '',
  'Copy fields and per-platform notes are in `docs/OFFSITE_SUBMISSION_PACK.md`.',
  'Use WhatsApp as the contact field until a mailbox exists. After submitting,',
  'record it in the CSV and verify it:',
  '',
  '```',
  'npm run seo:backlinks',
  '```',
  '',
  'Nothing on-page substitutes for this step. 7 clicks in three months is an',
  'authority result, not a copy result.',
  '',
  '## 5. Email and domain — two decisions',
  '',
  '- **Email:** enable Cloudflare Email Routing for a real mailbox. Until then the',
  '  site publishes only WhatsApp, because every message to the old address',
  '  bounced. When it exists, the address returns in the footer, `/contact/`,',
  '  `/about/`, the `Organization` schema and the three machine-readable files —',
  '  one commit, six places.',
  '- **Domain:** confirm whether `aitoolspak.com` is yours. If it is, a permanent',
  '  redirect to `aitoolspk.tech` is a Cloudflare rule. If it is not, nothing to do.',
  '',
  '## What this file cannot do',
  '',
  'It cannot click Verify, request indexing, approve a supplier, or submit a',
  'listing. Those need an account or a person. Everything else is code and is',
  'already committed.',
  '',
];

mkdirSync('reports', { recursive: true });
writeFileSync(path.join('reports', 'OWNER_ACTIONS.md'), lines.join('\n'));
console.log(
  `Wrote reports/OWNER_ACTIONS.md — ${pending.length} pending quotes, ${backlinks.length} backlink targets, ${
    indexStatus
      ? `${indexStatus.notIndexed?.length ?? 0} URLs not passing`
      : 'no inspection run yet'
  }.`
);
